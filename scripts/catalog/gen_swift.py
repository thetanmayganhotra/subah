#!/usr/bin/env python3
"""verified.jsonl -> Sources/Subah/CatalogData.swift (title|artist|tags|durationMs per line)."""
import json, os, re, unicodedata
D = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(D, "..", "..", "Sources", "Subah", "CatalogData.swift")
def norm(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return " ".join(re.sub(r"[^a-z0-9 ]", " ", re.sub(r"\s*[\(\[].*?[\)\]]", "", s)).split())
rows = [json.loads(l) for l in open(os.path.join(D, "verified.jsonl"), encoding="utf-8")]
ok = [r for r in rows if r["ok"]]; bad = [r for r in rows if not r["ok"]]
COMPOSERS = {"Claude Debussy", "Erik Satie", "Edvard Grieg", "Antonio Vivaldi", "Johann Pachelbel", "Wolfgang Amadeus Mozart", "Johann Sebastian Bach"}
def words(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return {w for w in re.sub(r"[^a-z0-9 ]", " ", s).split() if len(w) > 2 and w not in ("the", "and", "feat")}
seen, lines = set(), []
for r in ok:
    want_artist = r["want"].split(" — ", 1)[1]
    if want_artist in COMPOSERS:
        r["artist"] = want_artist            # classical: credit the composer, performer varies
    elif not (set().union(*[words(a) for a in want_artist.split("/")]) & words(r["artist"])):
        continue                              # a different artist's recording slipped through: drop it
    k = (norm(r["title"]), norm(r["artist"]).split(" ")[0] if norm(r["artist"]) else "")
    if k in seen: continue
    seen.add(k)
    t = r["title"].replace("|", "/").replace("\\", "")
    a = r["artist"].replace("|", "/").replace("\\", "")
    ms = r["ms"] if 120_000 <= r["ms"] <= 480_000 else 0   # implausible lengths (edits, intros) = unknown
    lines.append(f'{t}|{a}|{" ".join(r["tags"])}|{ms}')
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/catalog/gen_swift.py from verified.jsonl. Do not edit by hand.\n")
    f.write("enum CatalogData {\n    static let raw = \"\"\"\n" + "\n".join(lines) + "\n\"\"\"\n}\n")
print(f"verified {len(ok)} of {len(rows)}; wrote {len(lines)} unique songs")
open(os.path.join(D, "rejected.txt"), "w", encoding="utf-8").write("\n".join(r["want"] for r in bad))
